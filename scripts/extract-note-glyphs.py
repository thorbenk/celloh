"""Extract Bravura outlines as SVG path data, without a runtime font dependency.

Run: uv run scripts/extract-note-glyphs.py
Add SMuFL names/codepoints to GLYPHS below to extract additional symbols (e.g. rests).
Coordinates use the app's 20-unit staff space, SVG's downward y axis, and centered
noteheads. Flag origins stay at the stem tip. Stem anchors come from Bravura's
SMuFL metadata, not estimates of the glyph's bounding box.
"""

import io
import json
import subprocess
from pathlib import Path
from urllib.request import urlopen

from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.pens.transformPen import TransformPen
from fontTools.ttLib import TTFont

ROOT = Path(__file__).resolve().parents[1]
REVISION = "37b194378b710cc40e406ab6c4b07608bb9548ae"
SOURCE = f"https://raw.githubusercontent.com/steinbergmedia/bravura/{REVISION}"
STAFF_SPACE = 20
GLYPHS = {
    "noteheadWhole": 0xE0A2,
    "noteheadHalf": 0xE0A3,
    "noteheadBlack": 0xE0A4,
    "flag8thUp": 0xE240,
    "flag8thDown": 0xE241,
    "flag16thUp": 0xE242,
    "flag16thDown": 0xE243,
}


def download(path: str) -> bytes:
    with urlopen(f"{SOURCE}/{path}", timeout=30) as response:
        return response.read()


def svg_number(value: float) -> str:
    return str(round(value, 4)).removesuffix(".0")


def main() -> None:
    font = TTFont(io.BytesIO(download("redist/otf/Bravura.otf")))
    metadata = json.loads(download("redist/Bravura.json"))
    license_text = download("LICENSE.txt")
    glyph_set = font.getGlyphSet()
    cmap = font.getBestCmap()
    # SMuFL fonts use four staff spaces per em.
    scale = STAFF_SPACE / (font["head"].unitsPerEm / 4)
    output = [
        "// Generated by scripts/extract-note-glyphs.py; do not edit by hand.",
        f"// Bravura {REVISION}; SIL OFL 1.1 (bravura-LICENSE.txt).",
        "// SVG coordinates, 20 units per staff space; noteheads centered on (0, 0).",
        "export const MUSIC_GLYPHS = {",
    ]
    for name, codepoint in GLYPHS.items():
        width = metadata["glyphBBoxes"][name]["bBoxNE"][0] * STAFF_SPACE
        offset = -width / 2 if name.startswith("notehead") else 0
        pen = SVGPathPen(glyph_set, ntos=svg_number)
        glyph_set[cmap[codepoint]].draw(TransformPen(pen, (scale, 0, 0, -scale, offset, 0)))
        path = pen.getCommands()
        output.append(f"  {name}: {{")
        output.append(f"    path: '{path}',")
        if name.startswith("notehead"):
            # A solid backing hides staff/ledger lines inside hollow noteheads.
            output.append(f"    outline: '{path.split('Z')[0]}Z',")
            output.append(f"    width: {svg_number(width)},")
            anchors = metadata["glyphsWithAnchors"].get(name, {})
            for field, anchor in [("stemUp", "stemUpSE"), ("stemDown", "stemDownNW")]:
                if anchor in anchors:
                    x, y = anchors[anchor]
                    output.append(
                        f"    {field}: [{svg_number(x * STAFF_SPACE + offset)}, "
                        f"{svg_number(-y * STAFF_SPACE)}],"
                    )
        output.append("  },")
    output.append("} as const;")
    destination = ROOT / "src/assets/music-glyphs.ts"
    destination.write_text("\n".join(output) + "\n")
    (ROOT / "src/assets/bravura-LICENSE.txt").write_bytes(license_text)
    subprocess.run(
        [str(ROOT / "node_modules/.bin/prettier"), "--write", str(destination)], check=True
    )
    print(f"Extracted {len(GLYPHS)} SVG glyphs into src/assets/music-glyphs.ts")


if __name__ == "__main__":
    main()
